import 'dart:convert';
import 'dart:io';

import 'package:archive/archive.dart';
import 'package:path_provider/path_provider.dart';

import 'arifa_brain.dart';
import 'models.dart';

class ApkBuilderException implements Exception {
  final String message;
  ApkBuilderException(this.message);

  @override
  String toString() => message;
}

/// On-device "APK builder" pipeline.
///
/// A Flutter app on Android cannot run `flutter build apk` — there is no SDK,
/// JDK or Gradle toolchain inside an app process. No server is involved:
/// ARIFA does the parts that ARE possible here: generate a complete Flutter
/// project, ask the AI to review it, self-repair reported issues, then package
/// the source as a zip with a one-command build script.
class ApkBuilder {
  ApkBuilder({required ArifaBrain brain}) : _brain = brain;

  final ArifaBrain _brain;

  Future<BuildResult> buildWithAutoFix(
    String request, {
    int maxAttempts = 2,
    void Function(String stage, String detail)? onProgress,
  }) async {
    GeneratedApp? app;
    String? issue;

    for (var attempt = 1; attempt <= maxAttempts; attempt++) {
      onProgress?.call(
        'generate',
        '${attempt} নম্বর চেষ্টায় কোড তৈরি করছি Emon Bhai...',
      );
      app = await _brain.generateApp(
        request,
        previous: app,
        errorLog: issue,
      );

      onProgress?.call('review', 'AI দিয়ে কোড চেক করছি...');
      final review = (await _brain.reviewApp(app)).trim();
      if (_looksFine(review)) {
        final zip = await saveSourceZip(app);
        return BuildResult(
          app: app,
          zipPath: zip,
          attempts: attempt,
          review: review,
        );
      }
      issue = review;
      onProgress?.call('fix', 'সমস্যা ধরেছি, নিজে ঠিক করে আবার লিখছি...');
    }

    // Still give Emon Bhai the best generated source instead of failing hard.
    final zip = await saveSourceZip(app!);
    return BuildResult(
      app: app,
      zipPath: zip,
      attempts: maxAttempts,
      review: issue ?? 'AI review কোনো সমস্যা ধরতে পারেনি Emon Bhai।',
    );
  }

  bool _looksFine(String review) {
    if (review.isEmpty) return true;
    final r = review.toLowerCase().trim();
    return r == 'ok' ||
        r == 'ok.' ||
        r.startsWith('ok ') ||
        r.startsWith('সব ঠিক') ||
        r.startsWith('কোনো সমস্যা নেই');
  }

  Future<String> saveSourceZip(GeneratedApp app) async {
    final dir = await getApplicationDocumentsDirectory();
    final safeName = _safeName(app.name);
    final outDir = Directory('${dir.path}/arifa_projects/$safeName');
    if (!outDir.existsSync()) outDir.createSync(recursive: true);

    final entries = <CodeBlock>[
      ...app.files.map(
        (f) => CodeBlock(
          path: _safePath(f.path),
          language: f.language,
          content: f.content,
        ),
      ),
      const CodeBlock(
        path: 'build_apk.sh',
        language: 'bash',
        content: '''#!/usr/bin/env bash
set -euo pipefail
flutter pub get
flutter build apk --release
echo "APK: build/app/outputs/flutter-apk/app-release.apk"
''',
      ),
      CodeBlock(
        path: 'README_ARIFA.txt',
        language: 'text',
        content: '''${app.name}
${app.summary}

Generated by ARIFA for Emon Bhai ♥

Build this project on a machine that has the Flutter SDK + Android SDK + JDK:

    bash build_apk.sh

or manually:

    flutter pub get
    flutter build apk --release

On aarch64 Termux use:

    flutter build apk --release --target-platform android-arm64 --no-tree-shake-icons

The APK appears at build/app/outputs/flutter-apk/app-release.apk.
API keys are NOT included in this project.
''',
      ),
    ];

    for (final file in entries) {
      final f = File('${outDir.path}/${file.path}');
      f.parent.createSync(recursive: true);
      f.writeAsStringSync(file.content);
    }

    final archive = Archive();
    for (final file in entries) {
      final bytes = utf8.encode(file.content);
      archive.addFile(ArchiveFile(file.path, bytes.length, bytes));
    }
    final zipBytes = ZipEncoder().encode(archive) ?? <int>[];
    final zip = File('${dir.path}/arifa_projects/$safeName.zip');
    zip.writeAsBytesSync(zipBytes);
    return zip.path;
  }

  String _safeName(String raw) {
    final s = raw.toLowerCase().replaceAll(RegExp(r'[^a-z0-9_]+'), '_');
    final trimmed = s.replaceAll(RegExp(r'^_+|_+$'), '');
    return trimmed.isEmpty ? 'arifa_app' : trimmed;
  }

  String _safePath(String raw) {
    final cleaned = raw.replaceAll('\\', '/').replaceFirst(RegExp(r'^(\./|/)+'), '');
    final parts = cleaned
        .split('/')
        .where((p) => p.isNotEmpty && p != '.' && p != '..')
        .toList();
    return parts.isEmpty ? 'snippet.txt' : parts.join('/');
  }
}

class BuildResult {
  final GeneratedApp app;
  final String zipPath;
  final int attempts;
  final String review;

  const BuildResult({
    required this.app,
    required this.zipPath,
    required this.attempts,
    required this.review,
  });
}
